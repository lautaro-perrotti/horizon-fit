import {spawnSync} from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const script=path.join(root,'scripts/framework-store.mjs');
const example=JSON.parse(fs.readFileSync(path.join(root,'framework/store.example.json'),'utf8'));
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'hf-fw-cli-'));
const remote=path.join(tmp,'remote.json');
fs.writeFileSync(remote,JSON.stringify({slug:'cli-test',name:'Marca',storefrontUrl:'https://shop.example',apiUrl:'https://api.example',ports:{storefront:8920,api:8921}}));
const reset=spawnSync(process.execPath,[script,'reset',remote],{encoding:'utf8',windowsHide:true});
assert.notEqual(reset.status,0,'reset must refuse a remote host');
assert.match(`${reset.stderr}${reset.stdout}`,/instancia local/,'reset error names the local-only rule');
const seed=spawnSync(process.execPath,[script,'seed',remote],{encoding:'utf8',windowsHide:true});
assert.notEqual(seed.status,0,'seed must refuse a remote host');
assert.match(`${seed.stderr}${seed.stdout}`,/instancia local/,'seed error names the local-only rule');
const source=fs.readFileSync(script,'utf8');
assert.match(source,/Producto de ejemplo 1/);
assert.match(source,/Producto de ejemplo 2/);
assert.ok(!source.includes('004-TOP-BOR'),'seed catalog must not copy Horizon Fit SKUs');
const doctor=spawnSync(process.execPath,[script,'doctor',path.join(root,'framework/store.example.json')],{encoding:'utf8',windowsHide:true});
assert.equal(doctor.status,0,doctor.stderr);
const report=JSON.parse(doctor.stdout);
assert.equal(report.tracking.ga4.verified,false);
assert.equal(report.tracking.googleAds.verified,false);
assert.equal(report.tracking.metaPixel.verified,false);
assert.equal(report.tracking.metaCapi.verified,false);
assert.equal(report.tracking.metaPixel.configured,false);
assert.equal(report.tracking.ga4.configured,false);
assert.ok(!JSON.stringify(report).includes('HF_META_CAPI_ACCESS_TOKEN='));
assert.ok(!JSON.stringify(report).includes('"verified":true'));
assert.equal(report.store,'Casa Sur');
const doctorSlug='cli-doctor';
const doctorDir=path.join(root,'framework/instances',doctorSlug);
fs.mkdirSync(doctorDir,{recursive:true});
fs.writeFileSync(path.join(doctorDir,'.env'),'HF_META_CAPI_ACCESS_TOKEN=EAAG-super-secret-token\nDB_PASSWORD=secret-db-password\nHF_CACHE_WEBHOOK_SECRET=webhook-secret-value\n');
const doctorCfg=path.join(tmp,'doctor.json');
fs.writeFileSync(doctorCfg,JSON.stringify({...example,slug:doctorSlug,tracking:{enabled:true,ga4Id:'G-EXAMPLE',googleAdsId:'',googleAdsPurchaseLabel:'',metaPixelId:'123456789'}}));
const doctorSecret=spawnSync(process.execPath,[script,'doctor',doctorCfg],{encoding:'utf8',windowsHide:true});
assert.equal(doctorSecret.status,0,doctorSecret.stderr);
const secretOut=`${doctorSecret.stdout}${doctorSecret.stderr}`;
assert.ok(!secretOut.includes('EAAG-super-secret-token'),'doctor must not print the CAPI token');
assert.ok(!secretOut.includes('secret-db-password'),'doctor must not print the database password');
assert.ok(!secretOut.includes('webhook-secret-value'),'doctor must not print the webhook secret');
const secretReport=JSON.parse(doctorSecret.stdout);
assert.equal(secretReport.tracking.ga4.configured,true);
assert.equal(secretReport.tracking.ga4.verified,false);
assert.equal(secretReport.tracking.metaCapi.configured,true);
assert.equal(secretReport.tracking.metaCapi.verified,false);
assert.equal(secretReport.secrets.metaCapi,true);
const isolationSlug='cli-casa-sur';
const isolationDir=path.join(root,'framework/instances',isolationSlug);
fs.rmSync(isolationDir,{recursive:true,force:true});
const isolationCfg=path.join(tmp,'casa-sur.json');
fs.writeFileSync(isolationCfg,JSON.stringify({...example,slug:isolationSlug,ports:{storefront:8930,api:8931}}));
const build=spawnSync(process.execPath,[script,'build',isolationCfg],{encoding:'utf8',windowsHide:true,timeout:180000});
assert.equal(build.status,0,build.stderr||build.stdout);
const publicDir=path.join(isolationDir,'public');
const html=fs.readFileSync(path.join(publicDir,'index.html'),'utf8');
const bootstrapMatch=html.match(/window\.HF_STOREFRONT_CONFIG=(\{.*\});<\/script>/);
assert.ok(bootstrapMatch,'built index injects HF_STOREFRONT_CONFIG');
const bootstrap=JSON.parse(bootstrapMatch[1]);
assert.equal(bootstrap.name,'Casa Sur');
assert.equal(bootstrap.whatsappUrl,'');
assert.equal(bootstrap.trackingEnabled,false);
assert.equal(bootstrap.ga4Id,'');
assert.equal(bootstrap.metaPixelId,'');
assert.deepEqual(bootstrap.payments.installments,[]);
assert.equal(bootstrap.payments.setDiscountPercent,0);
assert.equal(bootstrap.shipping.nationwide,false);
assert.equal(bootstrap.social.instagram,'');
assert.equal(bootstrap.infoPages['/envios-y-entregas'].title,'');
assert.deepEqual(bootstrap.socialUrls,[]);
const forbidden=[/horizonfit/i,/Horizon Fit/,/@horizonfit/i,/541131150999/,/G-8TL56B3B8X/,/3 y 6 cuotas/i,/instagram\.com\/horizonfit/i,/tiktok\.com\/@horizon\.fit/i];
const textExt=new Set(['.html','.js','.json','.css','.svg','.txt','.xml','.map','.md']);
const leaks=[];
(function walk(dir){for(const entry of fs.readdirSync(dir,{withFileTypes:true})){const full=path.join(dir,entry.name);if(entry.isDirectory())walk(full);else if(textExt.has(path.extname(full).toLowerCase())){const text=fs.readFileSync(full,'utf8');for(const pattern of forbidden)if(pattern.test(text))leaks.push(`${path.relative(publicDir,full)} ${pattern}`);}}})(publicDir);
assert.equal(leaks.length,0,`Casa Sur public/ leaked Horizon Fit identity:\n${leaks.slice(0,20).join('\n')}`);
fs.rmSync(isolationDir,{recursive:true,force:true});
fs.rmSync(doctorDir,{recursive:true,force:true});
fs.rmSync(path.join(root,`reports/framework-doctor-${doctorSlug}.json`),{force:true});
fs.rmSync(tmp,{recursive:true,force:true});
console.log('OK reset/seed refused for remote hosts; doctor never marks tracking verified; Casa Sur public/ is isolated');
