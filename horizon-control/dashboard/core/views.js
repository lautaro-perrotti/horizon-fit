export function viewById(id) {
  return VIEWS.find((view) => view.id === id) ?? null;
}

export function hrefFor(id, param) {
  const view = viewById(id);
  if (!view) return "#/";
  const base = view.route.replace(/\/:[^/]+\??$/, "");
  return `#${base || "/"}${param ? `/${encodeURIComponent(param)}` : ""}`;
}
